/** 按 ID 快速查找 */
export const elastomerMap: Record<string, ElastomerNode> =
  Object.fromEntries(elastomerNodes.map(n => [n.id, n]));

/** 获取某节点的所有子节点（一级） */
export function getChildren(id: string): ElastomerNode[] {
  const node = elastomerMap[id];
  return (node?.childIds ?? []).map(cid => elastomerMap[cid]).filter(Boolean);
}

/** 获取某节点的所有后代（递归） */
export function getDescendants(id: string): ElastomerNode[] {
  const children = getChildren(id);
  return children.flatMap(c => [c, ...getDescendants(c.id)]);
}
